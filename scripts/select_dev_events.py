"""Select the development events for tool demonstrations (metadata only; no detector outcomes are looked at).

Development pool: INSTANCE sample events metadata rows with network IV, channel family HH, trace_dt_s 0.01 and
trace_npts 12000 (the same eligibility as the Stage 1 pool) whose EVENT ID has no trace in the frozen Stage 1 draw
(docs/cohort_stage1_traces.txt). The paused pre-registered study is therefore not contaminated at event level.

Rule (fixed before any real-event run): events are ranked by their number of pool stations. Every event with at
least MIN_STATIONS (8) stations is selected. If fewer than N (3) events qualify, the remaining slots are filled by a
seeded random choice among the events with the largest remaining station count (ties sorted by event id, then
random.Random(SEED).sample). The relaxation is recorded in the output.

    python scripts/select_dev_events.py --out docs/dev_events.txt
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import random
from collections import defaultdict
from pathlib import Path

SEED = 20261110
N_EVENTS = 3
MIN_STATIONS = 8


def eligible(row: dict[str, str]) -> bool:
    parts = row["trace_name"].split(".")
    return (
        len(parts) == 5
        and parts[1] == "IV"
        and parts[4] == "HH"
        and float(row["trace_dt_s"]) == 0.01
        and int(row["trace_npts"]) == 12000
    )


def dev_pool(rows: list[dict[str, str]], draw_names: set[str]) -> dict[str, list[str]]:
    """event id -> sorted trace names, for pool events that have no trace in the frozen draw."""
    by_name = {r["trace_name"]: r for r in rows}
    draw_events = {by_name[n]["source_id"] for n in draw_names if n in by_name}
    events: dict[str, list[str]] = defaultdict(list)
    for r in rows:
        if eligible(r) and r["source_id"] not in draw_events:
            events[r["source_id"]].append(r["trace_name"])
    return {e: sorted(v) for e, v in events.items()}


def choose(
    pool: dict[str, list[str]], n: int = N_EVENTS, min_stations: int = MIN_STATIONS, seed: int = SEED
) -> tuple[list[str], str]:
    qualifying = sorted(e for e, t in pool.items() if len(t) >= min_stations)
    chosen = qualifying[:n]
    note = f"{len(qualifying)} event(s) have at least {min_stations} stations: all selected."
    if len(chosen) < n:
        rest = sorted((e for e in pool if e not in chosen), key=lambda e: (-len(pool[e]), e))
        top = len(pool[rest[0]])
        tied = sorted(e for e in rest if len(pool[e]) == top)
        extra = random.Random(seed).sample(tied, n - len(chosen))
        chosen += sorted(extra)
        note += (
            f" Rule relaxed for the remaining {n - len(chosen) + len(extra)} slot(s): chosen with random.Random({seed})"
            f".sample among the {len(tied)} events with {top} stations (sorted by event id)."
        )
    return chosen, note


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--csv", default="data/instance_sample/metadata/metadata_Instance_events_10k.csv")
    ap.add_argument("--draw", default="docs/cohort_stage1_traces.txt")
    ap.add_argument("--out", default="docs/dev_events.txt")
    args = ap.parse_args()
    with open(args.csv, newline="") as f:
        rows = list(csv.DictReader(f))
    draw_text = Path(args.draw).read_bytes()
    pool = dev_pool(rows, set(draw_text.decode().split()))
    chosen, note = choose(pool)
    counts = sorted((len(t) for t in pool.values()), reverse=True)
    lines = [
        "# Development events for QuakeNode tool demonstrations (generated by scripts/select_dev_events.py)",
        "# Not chosen from any detector outcome. NOT part of the frozen Stage 1 draw.",
        f"# Frozen draw file {args.draw} sha256 {hashlib.sha256(draw_text).hexdigest()}",
        "# Pool: IV/HH/Z/100 Hz/12000-sample INSTANCE sample traces whose event id has no trace in the frozen draw",
        f"# Pool size: {sum(counts)} traces in {len(pool)} events; stations per event (sorted): {counts}",
        f"# Rule: {note}",
        f"# Selection seed (used only if the rule had to be relaxed): {SEED}",
        "# Format: event_id <tab> number_of_stations <tab> trace names (comma separated)",
    ]
    lines += [f"{e}\t{len(pool[e])}\t{','.join(pool[e])}" for e in chosen]
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:8]))
    print("selected:", [(e, len(pool[e])) for e in chosen])


if __name__ == "__main__":
    main()
