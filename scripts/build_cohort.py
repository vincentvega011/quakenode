"""Build the Stage 1 cohort manifest and summary from the frozen list and the fetched raw miniSEED.

Metadata, file-level checks and exclusions only; no detector or preprocessing comparison. Exclusions are applied in
the pre-declared order: fetch_failed, native_rate_not_100hz, gaps_or_overlaps, raw_does_not_cover_window,
hdf5_all_zero, grid_offset_gt_0.5_sample. Excluded traces are NOT replaced.

NOTE on the last criterion: the window is aligned to the NEAREST raw sample, so the offset between the metadata
start and the chosen raw sample is at most 0.5 sample by construction; the criterion can never trigger. The offset
distribution is reported instead.

    python scripts/build_cohort.py [--partial]
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from collections import Counter
from pathlib import Path

import numpy as np

from quakenode.data import TraceRecord, load_raw_window, load_release_z
from quakenode.manifest import DatasetRecord, RunManifest

REASONS = (
    "fetch_failed",
    "native_rate_not_100hz",
    "gaps_or_overlaps",
    "raw_does_not_cover_window",
    "hdf5_all_zero",
    "grid_offset_gt_0.5_sample",
)
WARMUPS_S = (10, 12, 15, 20, 30, 80, 82)
PRE_P_THRESHOLDS_S = (5, 10, 15, 20, 30, 60, 80)
N_SAMPLES = 12000


def q(values, qs=(0, 25, 50, 75, 100)):
    if len(values) == 0:
        return None
    return [round(float(x), 3) for x in np.percentile(np.asarray(values, dtype=float), qs)]


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_fetch_log(path: Path) -> dict[str, dict]:
    last: dict[str, dict] = {}
    for line in path.read_text().splitlines():
        if line.strip():
            e = json.loads(line)
            last[e["trace"]] = e
    return last


def scorable_table(pre_p_s: np.ndarray) -> dict:
    return {
        f"warmup_{w}s": {
            "frac_P_minus_W_ge_0": float(np.mean(pre_p_s - w >= 0)),
            "frac_P_minus_W_ge_3": float(np.mean(pre_p_s - w >= 3)),
            "frac_P_minus_W_ge_5": float(np.mean(pre_p_s - w >= 5)),
        }
        for w in WARMUPS_S
    }


def render_summary(s: dict) -> str:
    """Markdown for docs/cohort_stage1_summary.md from the summary dict."""
    pct = lambda x: "n/a" if x is None else f"{100 * x:.1f}%"  # noqa: E731
    status = "COMPLETE" if s["complete"] else f"DRAFT, INCOMPLETE ({s['n_pending']} traces not fetched yet)"
    lines = [
        "# Stage 1 cohort summary",
        "",
        "Research prototype, not an operational warning system. Metadata and file-level facts only; no detector or",
        "preprocessing comparison has been run on this cohort. Generated by `scripts/build_cohort.py`.",
        "",
        f"Status: **{status}**. Cohort list `docs/cohort_stage1_traces.txt` (sha256 `{s['cohort_sha256']}`), "
        f"{s['n_drawn']} traces drawn from the IV/HH/Z/100 Hz/12,000-sample pool (seed 20261105). "
        "Excluded traces are not replaced.",
        "",
        "## Exclusions (pre-declared order)",
        "",
        "| reason | count |",
        "|---|---|",
    ]
    lines += [f"| `{k}` | {v} |" for k, v in s["exclusions"].items()]
    lines += [
        f"| **comparable** | **{s['comparable']}** |",
        "",
        f"Comparable traces: {s['comparable_events']} events, {s['comparable_stations']} stations.",
        "",
        "`grid_offset_gt_0.5_sample` cannot trigger: the window is aligned to the nearest raw sample, so the offset is "
        "at most 0.5 sample by construction. Observed absolute offset distribution (samples, 0.1-sample bins "
        f"from 0): {s['grid_offset_samples']['abs_histogram_0.1_sample_bins']}; max |offset| "
        f"{s['grid_offset_samples']['max_abs']} sample ({s['grid_offset_samples']['abs_offset_ms_max']} ms).",
        "",
        "## Comparable-cohort distributions (min, Q1, median, Q3, max)",
        "",
        f"- Magnitude: {s['magnitude_min_q25_med_q75_max']}",
        f"- Epicentral distance (km): {s['epicentral_distance_km_min_q25_med_q75_max']}",
        f"- P time in window = pre-P length (s): {s['P_time_in_window_s_min_q25_med_q75_max']}",
        f"- Post-P length (s): {s['post_P_s_min_q25_med_q75_max']}",
        f"- Stated P uncertainty (s) counts: {s['P_uncertainty_s_counts']}",
        "",
        "Fraction of comparable traces with at least T seconds before P:",
        "",
        "| T (s) | " + " | ".join(s["pre_P_fraction_at_least_s"]) + " |",
        "|---|" + "---|" * len(s["pre_P_fraction_at_least_s"]),
        "| fraction | " + " | ".join(pct(v) for v in s["pre_P_fraction_at_least_s"].values()) + " |",
        "",
        "Fraction scorable for a detector with warm-up W (scoring can start at least 0, 3 or 5 s before P):",
        "",
        "| W (s) | P-W >= 0 | P-W >= 3 | P-W >= 5 |",
        "|---|---|---|---|",
    ]
    for k, v in (s["scorable_by_warmup"] or {}).items():
        lines.append(f"| {k.replace('warmup_', '').replace('s', '')} | {pct(v['frac_P_minus_W_ge_0'])} | "
                     f"{pct(v['frac_P_minus_W_ge_3'])} | {pct(v['frac_P_minus_W_ge_5'])} |")  # fmt: skip
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data-dir", default="data/instance_sample")
    ap.add_argument("--cohort", default="docs/cohort_stage1_traces.txt")
    ap.add_argument("--raw-dir", default="data/raw/cohort")
    ap.add_argument("--out-dir", default="data/cohort")
    ap.add_argument("--summary", default="docs/cohort_stage1_summary.md")
    ap.add_argument("--partial", action="store_true", help="allow traces without a final fetch-log entry (draft)")
    args = ap.parse_args()
    root, raw_dir, out_dir = Path(args.data_dir), Path(args.raw_dir), Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    names = Path(args.cohort).read_text().split()
    cohort_sha = hashlib.sha256(Path(args.cohort).read_bytes()).hexdigest()
    with open(root / "metadata/metadata_Instance_events_10k.csv", newline="") as f:
        meta = {r["trace_name"]: r for r in csv.DictReader(f)}
    hdf5 = root / "data/Instance_events_counts_10k.hdf5"
    log = load_fetch_log(raw_dir / "fetch_log.jsonl")
    pending = [n for n in names if log.get(n, {}).get("status") not in ("ok", "empty")]
    if pending and not args.partial:
        raise SystemExit(
            f"{len(pending)} cohort traces have no final fetch-log entry; finish the fetch or use --partial"
        )

    rows, offsets = [], []
    for name in names:
        entry = log.get(name)
        rec = TraceRecord.from_metadata_row(meta[name], raw_mseed_sha256=(entry or {}).get("sha256"))
        row = {"trace_name": name, "status": "comparable", "reason": ""}
        if entry is None or entry["status"] not in ("ok", "empty"):
            row.update(status="pending", reason="not_fetched_yet")
            rows.append(row)
            continue
        path = raw_dir / entry["file"] if entry["status"] == "ok" else raw_dir / "missing"
        w = load_raw_window(path, rec.trace_start_time, N_SAMPLES, 100.0)
        if w.exclusion_reason:
            row.update(status="excluded", reason=w.exclusion_reason, detail=w.detail)
        else:
            offsets.append(w.offset_samples)
            row.update(offset_samples=w.offset_samples, first_raw_index=w.first_raw_index)
            if not load_release_z(hdf5, name).any():
                row.update(status="excluded", reason="hdf5_all_zero")
            elif abs(w.offset_samples) > 0.5:
                row.update(status="excluded", reason="grid_offset_gt_0.5_sample")
        rows.append(row)

    comparable = [r["trace_name"] for r in rows if r["status"] == "comparable"]
    reasons = Counter(r["reason"] for r in rows if r["status"] == "excluded")
    recs = [TraceRecord.from_metadata_row(meta[n]) for n in comparable]
    pre_p = np.array([r.p_sample / 100.0 for r in recs])
    post_p = 120.0 - pre_p
    offs = np.array(offsets)
    summary = {
        "complete": not pending,
        "n_pending": len(pending),
        "cohort_file": args.cohort,
        "cohort_sha256": cohort_sha,
        "n_drawn": len(names),
        "exclusions": {k: reasons.get(k, 0) for k in REASONS},
        "excluded_traces": {k: [r["trace_name"] for r in rows if r["reason"] == k] for k in REASONS},
        "comparable": len(comparable),
        "comparable_events": len({r.event_id for r in recs}),
        "comparable_stations": len({r.station for r in recs}),
        "magnitude_min_q25_med_q75_max": q([r.magnitude for r in recs if r.magnitude is not None]),
        "epicentral_distance_km_min_q25_med_q75_max": q(
            [r.epicentral_distance_km for r in recs if r.epicentral_distance_km is not None]
        ),
        "P_time_in_window_s_min_q25_med_q75_max": q(pre_p),
        "post_P_s_min_q25_med_q75_max": q(post_p),
        "P_uncertainty_s_counts": dict(Counter(str(r.p_uncertainty_s) for r in recs)),
        "pre_P_fraction_at_least_s": {
            str(t): float(np.mean(pre_p >= t)) if len(pre_p) else None for t in PRE_P_THRESHOLDS_S
        },
        "scorable_by_warmup": scorable_table(pre_p) if len(pre_p) else None,
        "grid_offset_samples": {
            "n": int(len(offs)),
            "min_q25_med_q75_max": q(offs),
            "max_abs": round(float(np.abs(offs).max()), 4) if len(offs) else None,
            "abs_histogram_0.1_sample_bins": (
                np.histogram(np.abs(offs), bins=np.arange(0, 0.6, 0.1))[0].tolist() if len(offs) else None
            ),
            "abs_offset_ms_max": round(float(np.abs(offs).max() * 10.0), 2) if len(offs) else None,
        },
    }
    manifest = RunManifest.create(
        config={"cohort_sha256": cohort_sha, "seed": 20261105, "pool": "IV/HH/Z/100Hz/12000", "n_drawn": len(names)},
        seeds=[20261105],
        metric_definition_version="cohort_stage1_v1",
        repo_dir=Path.cwd(),
        datasets=[
            DatasetRecord(
                id="INSTANCE sample v3 events counts HDF5",
                doi="10.13127/instance",
                license_note="CC BY 4.0 per INGV INSTANCE page",
                sha256=sha256_file(hdf5),
            ),
            DatasetRecord(
                id="INGV FDSN dataselect miniSEED, cohort (data/raw/cohort; per-file sha256 in fetch_log.jsonl)",
                source_url="https://webservices.ingv.it/fdsnws/dataselect/1/query",
                license_note="IV restrictedStatus=open per INGV station service; EIDA Italy policy: CC BY 4.0 mostly",
                sha256=sha256_file(raw_dir / "fetch_log.jsonl"),
            ),
        ],
        output_paths=[str(out_dir / "manifest.json"), args.summary],
        exclusions=[f"{k}: {v}" for k, v in reasons.items()],
        warnings=([] if not pending else [f"incomplete: {len(pending)} traces not fetched yet"]),
    )
    (out_dir / "manifest.json").write_text(
        json.dumps({"summary": summary, "per_trace": rows, "manifest": manifest.to_dict()}, indent=2, sort_keys=True)
        + "\n"
    )
    Path(args.summary).write_text(render_summary(summary))
    (out_dir / "comparable_traces.txt").write_text("\n".join(comparable) + "\n")
    print(
        json.dumps({k: summary[k] for k in ("complete", "n_pending", "n_drawn", "exclusions", "comparable")}, indent=2)
    )


if __name__ == "__main__":
    main()
